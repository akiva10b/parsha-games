#!/usr/bin/env node
/* Records every narrator line with a macOS voice and writes MP3s to
   audio/voice/, plus manifest.js telling the game which lines have a
   recording. Re-run after editing src/strings.js; unchanged lines are
   skipped, and recordings of removed lines are deleted.

     node tools/make-voice.mjs                     # best installed premium voice
     node tools/make-voice.mjs --voice "Zoe (Premium)" --rate 165 --force
     node tools/make-voice.mjs --list              # show usable voices

   Needs macOS `say` and ffmpeg (brew install ffmpeg). */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const outDir = path.join(root, 'audio', 'voice');
const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : dflt; };
const force = args.includes('--force');

// Load the game's own text so the recordings always match it.
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'src', 'strings.js'), 'utf8') +
  ';this.lines = allSpokenLines(); this.lineId = lineId; this.fixes = SPEAK_FIX;', ctx);

const voices = execFileSync('say', ['-v', '?'], { encoding: 'utf8' }).split('\n')
  .map((l) => l.match(/^(.+?)\s{2,}(\w\w_\w\w)\s+#/)).filter(Boolean)
  .map((m) => ({ name: m[1].trim(), lang: m[2] }))
  .filter((v) => v.lang.startsWith('en_') && /\((Premium|Enhanced)\)/.test(v.name));

if (args.includes('--list')) {
  console.log(voices.length ? voices.map((v) => `${v.name}  ${v.lang}`).join('\n') : 'No premium or enhanced English voices installed.');
  process.exit(0);
}

const prefer = ['Ava (Premium)', 'Zoe (Premium)', 'Evan (Premium)', 'Ava (Enhanced)', 'Zoe (Enhanced)', 'Samantha (Enhanced)'];
const voice = opt('--voice') || prefer.find((p) => voices.some((v) => v.name === p)) || (voices[0] && voices[0].name);
if (!voice) {
  console.error('No premium or enhanced English voice is installed.\n' +
    'Install one in System Settings → Accessibility → Spoken Content → System voice → Manage Voices… (e.g. Ava (Premium)).');
  process.exit(1);
}
const rate = opt('--rate', '170');

const spoken = (text) => {
  let s = text;
  for (const [re, rep] of ctx.fixes) s = s.replace(re, rep);
  return s;
};

fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'll-voice-'));
const manifest = {};
let made = 0;
for (const text of ctx.lines) {
  const id = ctx.lineId(text);
  const mp3 = path.join(outDir, id + '.mp3');
  if (force || !fs.existsSync(mp3)) {
    const aiff = path.join(tmp, id + '.aiff');
    execFileSync('say', ['-v', voice, '-r', rate, '-o', aiff, spoken(text)]);
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', aiff,
      '-af', 'silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse',
      '-ac', '1', '-ar', '44100', '-b:a', '80k', mp3]);
    made++;
    process.stdout.write('.');
  }
  manifest[id] = true;
}
fs.rmSync(tmp, { recursive: true, force: true });

for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.mp3') && !manifest[f.slice(0, -4)]) fs.unlinkSync(path.join(outDir, f));
}
fs.writeFileSync(path.join(outDir, 'manifest.js'),
  `/* Generated by tools/make-voice.mjs with "${voice}". Do not edit. */\n` +
  `const VOICE_FILES = ${JSON.stringify(manifest)};\n`);
console.log(`\n${voice}: ${made} recorded, ${ctx.lines.length} lines total → audio/voice/`);
